"""PDF pages: use the text layer of computer-made PDFs, render scanned pages for OCR.

PDFs that were generated by billing software (most e-mailed invoices) contain the exact
text with its position. Reading that is faster than OCR and has no misread digits.
Pages that only contain a picture (scanned paper) are rendered to an image for OCR.
"""

import logging
from typing import Any, List, Tuple

from .models import Page, Word

log = logging.getLogger(__name__)

# Text-layer coordinates are PDF points (1/72 inch). Scale them to about 144 dpi so text
# sizes are in the same range as OCR boxes on a photo.
TEXT_SCALE = 2.0


def read_pdf(path: str, use_text_layer: bool = True, min_characters: int = 40, render_dpi: int = 200
             ) -> List[Tuple[str, Any]]:
    """One entry per page: ("text", Page) when the text layer is usable, else ("image", BGR array)."""
    import numpy as np
    import pypdfium2 as pdfium

    try:
        document = pdfium.PdfDocument(path)
    except pdfium.PdfiumError as error:
        raise ValueError("Cannot read PDF {}: {}".format(path.rsplit("/", 1)[-1].rsplit("\\", 1)[-1], error))
    result: List[Tuple[str, Any]] = []
    try:
        for index in range(len(document)):
            page = document[index]
            if use_text_layer and page.get_rotation() == 0:
                text_page = _text_layer_page(page)
                if sum(len(w.text.replace(" ", "")) for w in text_page.words) >= min_characters:
                    result.append(("text", text_page))
                    continue
            image = page.render(scale=render_dpi / 72.0).to_pil().convert("RGB")
            result.append(("image", np.ascontiguousarray(np.asarray(image)[:, :, ::-1])))
    finally:
        document.close()
    return result


def _text_layer_page(page: Any) -> Page:
    import pypdfium2.raw as pdfium_c

    width, height = page.get_width(), page.get_height()
    text_page = page.get_textpage()
    glyphs = []  # (x1, y1, x2, y2, char, space before) in top-left coordinates
    space_before = False
    for i in range(text_page.count_chars()):
        char = text_page.get_text_range(i, 1)
        if not char or char.isspace():
            # Spaces pdfium adds itself between separately placed text do not count.
            if not pdfium_c.FPDFText_IsGenerated(text_page.raw, i):
                space_before = True
            continue
        left, bottom, right, top = text_page.get_charbox(i, loose=True)
        if right <= left or top <= bottom:
            continue
        glyphs.append((left * TEXT_SCALE, (height - top) * TEXT_SCALE,
                       right * TEXT_SCALE, (height - bottom) * TEXT_SCALE, char, space_before))
        space_before = False
    text_page.close()
    return Page(words=_group_words(glyphs), width=width * TEXT_SCALE, height=height * TEXT_SCALE, source="pdf-text")


Glyph = Tuple[float, float, float, float, str, bool]


def _group_words(glyphs: List[Glyph]) -> List[Word]:
    """Glyphs -> text boxes like the OCR engine makes: one box per run of text on a line,
    split at the gap to the next table cell. Text written with a real space character is one
    phrase ("Invoice No. : 42"); text placed separately splits at a smaller gap ("S.No." "Item")."""
    lines: List[List[Glyph]] = []
    for glyph in sorted(glyphs, key=lambda g: ((g[1] + g[3]) / 2, g[0])):
        cy, h = (glyph[1] + glyph[3]) / 2, glyph[3] - glyph[1]
        for line in reversed(lines[-6:]):
            ref = line[0]
            if abs((ref[1] + ref[3]) / 2 - cy) < 0.5 * min(h, ref[3] - ref[1]):
                line.append(glyph)
                break
        else:
            lines.append([glyph])

    words: List[Word] = []
    for line in lines:
        line.sort(key=lambda g: g[0])
        run = [line[0]]
        for glyph in line[1:]:
            prev = run[-1]
            h = max(prev[3] - prev[1], glyph[3] - glyph[1])
            if glyph[0] - prev[2] > (1.2 if glyph[5] else 0.6) * h:
                words.append(_to_word(run))
                run = [glyph]
            else:
                run.append(glyph)
        words.append(_to_word(run))
    return words


def _to_word(run: List[Glyph]) -> Word:
    text = run[0][4]
    for prev, glyph in zip(run, run[1:]):
        h = max(prev[3] - prev[1], glyph[3] - glyph[1])
        if glyph[5] or glyph[0] - prev[2] > 0.18 * h:
            text += " "
        text += glyph[4]
    return Word(text, 1.0, min(g[0] for g in run), min(g[1] for g in run),
                max(g[2] for g in run), max(g[3] for g in run))
